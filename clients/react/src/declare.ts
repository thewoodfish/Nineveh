import type { TableInfo } from './types.ts'

/**
 * The TypeScript a column's values arrive as.
 *
 * This is the one thing a hand-written type gets wrong. The API renders integers up to
 * 32 bits as JSON numbers and anything wider as decimal strings, because `Number()`
 * loses digits above 2^53 and does it silently — so a `u64` is a `string` here, and
 * code that multiplies one stops compiling instead of quietly being wrong.
 */
export function tsType(type: string): string {
  switch (type) {
    case 'bool':
      return 'boolean'
    // Up to 32 bits fits a JSON number exactly.
    case 'u8':
    case 'u16':
    case 'u32':
    case 'i8':
    case 'i16':
    case 'i32':
      return 'number'
    // Wider than that arrives as a decimal string.
    case 'u64':
    case 'u128':
    case 'u256':
    case 'i64':
    case 'i128':
    case 'i256':
      return 'string'
    // An address is `0x`-prefixed hex at full width; bytes are `0x`-prefixed hex too.
    case 'address':
    case 'string':
    case 'bytes':
      return 'string'
    // A Move struct, enum or vector, as the JSON the fullnode rendered.
    case 'json':
      return 'unknown'
    default:
      // A column type this package has not been taught. `unknown` keeps the row usable
      // and makes the one column it cannot name the only thing you have to cast.
      return 'unknown'
  }
}

/** A name that can be written bare in an interface, or must be quoted. */
function member(name: string): string {
  return /^[A-Za-z_$][A-Za-z0-9_$]*$/.test(name) ? name : JSON.stringify(name)
}

/**
 * A declaration file for a project's tables, to drop beside your source.
 *
 * It augments `NinevehTables`, which is what teaches `useTable` and `useLiveTable` the
 * names and the row shapes — so a mistyped table, a column that isn't there, or a `u64`
 * used as a number all become type errors rather than `undefined` at runtime.
 */
export function declaration(tables: readonly TableInfo[], project?: string): string {
  const where = project === undefined ? '' : `\n// Generated from ${project}`
  const rows = [...tables]
    .sort((a, b) => (a.name < b.name ? -1 : a.name > b.name ? 1 : 0))
    .map((table) => {
      const columns = table.columns.map((column) => {
        const optional = column.nullable ? ' | null' : ''
        return `      /** \`${column.type}\`${column.nullable ? ', nullable' : ''} */\n` +
          `      ${member(column.name)}: ${tsType(column.type)}${optional}`
      })
      const key = table.key.length === 0 ? 'no key' : table.key.join(', ')
      return (
        `    /**\n` +
        `     * \`${table.name}\` — ${table.kind}, keyed on ${key}.\n` +
        `     */\n` +
        `    ${member(table.name)}: {\n` +
        `${columns.join('\n')}\n` +
        `      /** The transaction that last wrote this row. */\n` +
        `      _version: string\n` +
        `    }`
      )
    })

  return `// Generated by \`nineveh-types\`. Do not edit — regenerate it instead.
//
// Every state table of your project, and the type each column's values arrive as.
//
// This file needs no importing. It augments the package, so what matters is that it is
// inside your tsconfig's \`include\` — somewhere the compiler reads, usually \`src/\`.${where}

import '@nineveh/react'

declare module '@nineveh/react' {
  interface NinevehTables {
${rows.join('\n')}
  }
}
`
}
